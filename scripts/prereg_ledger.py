"""Generate evals/validation/v1/PREREG_LEDGER.md from git history (dev-only; reads git, never edits a registration).

One row per pre-registration (`evals/validation/v1/PREREG_*.md`, `datasets/guard_bench/PREREG_*.md`): the sha256 of
its committed content, the commit that first added it and that commit's author date, any later commit to it, and each
evidence file it governs with the commit that first added that file. tests/test_prereg_ledger.py fails if the
committed ledger differs from a regeneration.

    python scripts/prereg_ledger.py           # rewrite the ledger
    python scripts/prereg_ledger.py --check   # exit 1 if the committed ledger is stale
"""

from __future__ import annotations

import argparse
import hashlib
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
LEDGER = "evals/validation/v1/PREREG_LEDGER.md"
REGISTRATION_GLOBS = ("evals/validation/v1/PREREG_*.md", "datasets/guard_bench/PREREG_*.md")
V1 = "evals/validation/v1"
# The evidence each registration governs: the result file the Trust Report reads (it names its registration in a
# top-level "preregistration" key where it has one), then the raw records committed with it for the same pass. A
# registration's own commit may also carry its seal (the detector's confirmatory.seal.json): part of the
# registration, not evidence.
GOVERNS = {
    "datasets/guard_bench/PREREG_heldout_v3.md": ["evals/guard_bench/claude_code_heldout_v3.json"],
    f"{V1}/PREREG_b3_single_question.md": [f"{V1}/b3_rubric_vs_plain_judge.json",
                                           f"{V1}/b3_rubric_vs_plain_judge/b3_answers.json"],
    f"{V1}/PREREG_compact_fix.md": [f"{V1}/compact_fix.json"],
    f"{V1}/PREREG_content_safety.md": [f"{V1}/content_safety.json", f"{V1}/content_safety/lg_raw.jsonl"],
    f"{V1}/PREREG_detector_v1.md": [f"{V1}/detector/detector_v1.json", f"{V1}/detector/scores.jsonl",
                                    f"{V1}/detector/lg3_raw.jsonl", f"{V1}/detector/lg3_subsample.json",
                                    f"{V1}/detector/dev_loso.json"],
    f"{V1}/PREREG_guard_on_fresh_transcripts.md": [f"{V1}/guard_on_fresh_transcripts.json"],
    f"{V1}/PREREG_guard_vs_detectors.md": [],  # the raw records and the result are listed once they are committed
    f"{V1}/PREREG_guard_on_real_transcripts.md": [f"{V1}/guard_on_transcripts.json"],
    f"{V1}/PREREG_guard_vs_llama_guard.md": [f"{V1}/guard_vs_llama_guard.json", f"{V1}/guard_vs_llama_guard/raw.jsonl"],
    f"{V1}/PREREG_local_grader.md": [f"{V1}/judge_eval_prob_qwen7b.json"],
    f"{V1}/PREREG_q1_toolloop.md": [f"{V1}/toolloop/judge_eval_toolloop_host_sonnet.json",
                                   f"{V1}/toolloop/judge_eval_toolloop_host_sonnet/judge.cassette.json"],
    f"{V1}/PREREG_q7_claims_v3.md": [f"{V1}/claims_v3/judge_eval_claims_v3_host_sonnet.json",
                                    f"{V1}/claims_v3/judge_eval_claims_v3_host_sonnet/judge.cassette.json"],
    f"{V1}/PREREG_step2_guard.md": [f"{V1}/step2_guard.json", f"{V1}/step2/lg_raw.jsonl", f"{V1}/step2/prior.jsonl"],
    f"{V1}/PREREG_step3_guard.md": [f"{V1}/step3_guard.json"],
    f"{V1}/PREREG_step4_agentdojo.md": [f"{V1}/step4_agentdojo.json", f"{V1}/agentdojo/heldout/qwen2.5-7b.jsonl"],
    f"{V1}/PREREG_step5_binding.md": [f"{V1}/step5_binding.json"],
}

HEADER = f"""# Pre-registration ledger

Generated by `python scripts/prereg_ledger.py` from git history; `tests/test_prereg_ledger.py` fails if this file
drifts from a regeneration. One row per registration (`{REGISTRATION_GLOBS[0]}`,
`{REGISTRATION_GLOBS[1]}`): the sha256 of its committed content, the commit that first added it and that commit's
author date, any later commit to it, and each evidence file it governs with the commit that first added that file.
Rows are in registration order. A registration's own commit may also carry its seal; a seal is part of the
registration, not evidence.
"""

FOOTER = """
Re-derive a row: `git log --diff-filter=A --format=%h%x09%ad --date=iso -- <file>` prints the commit that added the
file and its author date (the last line is the first add); `git log --format=%h%x09%ad --date=iso -- <file>` lists
every commit to it; `git show HEAD:<file> | sha256sum` gives the hash.
"""


def _git(root: pathlib.Path, *args: str) -> str:
    return subprocess.run(["git", *args], cwd=root, check=True, capture_output=True, text=True,
                          encoding="utf-8").stdout


def _commits(root: pathlib.Path, rel: str, *extra: str) -> list[dict]:
    """Commits touching `rel`, newest first: full sha, author date (ISO, the author's zone) and unix time."""
    out = _git(root, "log", *extra, "--format=%H%x09%ad%x09%at", "--date=iso", "--", rel)
    rows = [line.split("\t") for line in out.splitlines() if line.strip()]
    return [{"commit": sha, "date": date, "timestamp": int(ts)} for sha, date, ts in rows]


def first_commit(root: pathlib.Path, rel: str) -> dict:
    added = _commits(root, rel, "--diff-filter=A")
    if not added:
        raise SystemExit(f"{rel} is not committed: commit it before generating the ledger")
    return added[-1]


def committed_sha256(root: pathlib.Path, rel: str) -> str:
    return hashlib.sha256(subprocess.run(["git", "show", f"HEAD:{rel}"], cwd=root, check=True,
                                         capture_output=True).stdout).hexdigest()


def registrations(root: pathlib.Path) -> list[str]:
    found = sorted({p.relative_to(root).as_posix() for g in REGISTRATION_GLOBS for p in root.glob(g)} - {LEDGER})
    unmapped = [rel for rel in found if rel not in GOVERNS]
    if unmapped:
        raise SystemExit(f"name the evidence these registrations govern in GOVERNS: {', '.join(unmapped)}")
    return found


def ledger_rows(root: pathlib.Path = ROOT) -> list[dict]:
    rows = []
    for rel in registrations(root):
        first = first_commit(root, rel)
        later = [c for c in _commits(root, rel) if c["commit"] != first["commit"]][::-1]
        evidence = [{"path": ev, **first_commit(root, ev)} for ev in GOVERNS[rel]]
        rows.append({"registration": rel, "sha256": committed_sha256(root, rel), **first, "later": later,
                     "evidence": evidence})
    return sorted(rows, key=lambda r: (r["timestamp"], r["registration"]))


def _at(c: dict) -> str:
    return f"`{c['commit'][:7]}` {c['date']}"


def render(root: pathlib.Path = ROOT) -> str:
    lines = [HEADER, "| Registration | sha256 | Registered | Later commits to it | Evidence (first commit, author date) |",
             "|---|---|---|---|---|"]
    for r in ledger_rows(root):
        later = "<br>".join(_at(c) for c in r["later"]) or "none"
        evidence = "<br>".join(f"`{e['path']}`: {_at(e)}" for e in r["evidence"]) or "none yet"
        lines.append(f"| `{r['registration']}` | `{r['sha256']}` | {_at(r)} | {later} | {evidence} |")
    return "\n".join(lines) + "\n" + FOOTER


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed ledger differs from a regeneration")
    args = ap.parse_args(argv)
    text, path = render(ROOT), ROOT / LEDGER
    if args.check:
        current = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.is_file() else ""
        if current != text:
            print(f"{LEDGER} is stale: run python scripts/prereg_ledger.py", file=sys.stderr)
            return 1
        print(f"{LEDGER} matches git history")
        return 0
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {LEDGER}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
